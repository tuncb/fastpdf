"""Compile published Adobe mapping DATA, never third-party engine code.

Input: a directory containing cmap.zip, unicode.zip, glyphlist.txt,
zapfdingbats.txt, and agl-license.txt downloaded from the URLs below.
The checked-in output makes ordinary builds entirely offline.
"""
from pathlib import Path
from zipfile import ZipFile
import hashlib
import re
import sys
import zlib

root=Path(__file__).resolve().parents[1]
source=Path(sys.argv[1])
maps={}
licenses=[]
for archive in ["cmap.zip","unicode.zip"]:
    with ZipFile(source/archive) as z:
        for name in z.namelist():
            if "LICENSE" in name:
                licenses.append(z.read(name).decode("utf-8"))
            if name.endswith("/") or ("/CMap/" not in name and "/pdf2unicode/" not in name):
                continue
            text=z.read(name).decode("ascii")
            clean="\n".join(line.split("%",1)[0].strip() for line in text.splitlines())
            clean=re.sub(r"\s+"," ",clean)
            blocks=[]
            for pattern in [r"/[^\s]+ usecmap",r"/WMode [01] def",r"\d+ begincodespacerange .*? endcodespacerange",r"\d+ begincidchar .*? endcidchar",r"\d+ begincidrange .*? endcidrange",r"\d+ beginbfchar .*? endbfchar",r"\d+ beginbfrange .*? endbfrange"]:
                blocks.extend((match.start(),match.group()) for match in re.finditer(pattern,clean))
            maps[name.rsplit("/",1)[1]]="\n".join(block for _,block in sorted(blocks)).encode("ascii")

blob=bytearray()
index=[]
for name,data in sorted(maps.items()):
    encoded=zlib.compress(data,9)
    index.append((name,len(blob),len(encoded)))
    blob+=encoded

output=root/'src'/'font_data.inc'
with output.open('w',encoding='utf-8') as out:
    out.write('// Generated by scripts/generate-font-data.py. Mapping data: Adobe BSD license.\n')
    out.write('// See docs/FONT-DATA-LICENSE.txt. No third-party executable code.\n')
    out.write('static constexpr uint8_t cmap_bytes[] = {\n')
    for start in range(0,len(blob),32):
        out.write(','.join(f'0x{b:02x}' for b in blob[start:start+32])+',\n')
    out.write('};\nstruct BuiltinCMap { std::string_view name; uint32_t offset, size; };\n')
    out.write('static constexpr BuiltinCMap cmap_index[] = {\n')
    for name,offset,size in index:
        out.write(f'{{"{name}",{offset},{size}}},\n')
    out.write('};\nstruct GlyphName { std::string_view name; uint32_t unicode; };\n')
    out.write('static constexpr GlyphName adobe_glyph_names[] = {\n')
    names={}
    for filename in ['glyphlist.txt','zapfdingbats.txt']:
        for line in (source/filename).read_text(encoding='ascii').splitlines():
            if line and not line.startswith('#'):
                name,values=line.split(';')
                names[name]=int(values.split()[0],16)
    for name,value in sorted(names.items()):
        out.write(f'{{"{name}",0x{value:x}}},\n')
    out.write('};\n')

notice='Published character mapping data used by FastPDF\n\n'
notice+='The C++ PDF engine is independently implemented. Only character mapping\ntables are derived from the following Adobe projects:\n\n'
notice+='https://github.com/adobe-type-tools/cmap-resources\nhttps://github.com/adobe-type-tools/mapping-resources-pdf\nhttps://github.com/adobe-type-tools/agl-aglfn\n\n'
for name in ['cmap.zip','unicode.zip','glyphlist.txt','zapfdingbats.txt']:
    notice+=name+' SHA-256 '+hashlib.sha256((source/name).read_bytes()).hexdigest()+'\n'
notice+='\n'+'\n\n'.join(licenses)+'\n\n'+(source/'agl-license.txt').read_text(encoding='utf-8')
(root/'docs'/'FONT-DATA-LICENSE.txt').write_text(notice,encoding='utf-8')
print(f'{len(maps)} CMaps; {len(names)} glyph names; {len(blob)} compressed bytes')
